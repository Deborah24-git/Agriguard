import Link from "next/link";
import { MessageSquare } from "lucide-react";
import { Badge } from "@/components/ui/Badge";
import { SectionCard } from "@/components/ui/SectionCard";
import { formatRelative } from "@/lib/format";
import type { SmsLogDTO } from "@/types/sms";

const STATUS_VARIANT = {
  sent: "success",
  failed: "danger",
  skipped: "muted",
} as const;

interface DashboardSmsActivityProps {
  messages: SmsLogDTO[];
}

export function DashboardSmsActivity({
  messages,
}: DashboardSmsActivityProps) {
  return (
    <SectionCard
      title="SMS activity"
      description="Sandbox test messages and SMS alerts generated by the simulator."
      actions={
        <Link
          href="/settings"
          className="text-xs font-semibold text-primary hover:underline"
        >
          All SMS
        </Link>
      }
    >
      {messages.length === 0 ? (
        <div className="flex items-center gap-2 py-2 text-sm text-muted-foreground">
          <MessageSquare className="h-4 w-4" />
          No SMS activity yet. Send a sandbox test from Settings or run a sensor
          tick that detects an alert.
        </div>
      ) : (
        <ul className="divide-y divide-border">
          {messages.map((message) => (
            <li
              key={message.id}
              className="space-y-1 py-3 first:pt-0 last:pb-0"
            >
              <div className="flex flex-wrap items-center gap-2">
                <Badge
                  variant={
                    message.is_simulation || message.is_sandbox_test
                      ? "info"
                      : STATUS_VARIANT[message.status]
                  }
                >
                  {message.is_simulation
                    ? "simulated"
                    : message.is_sandbox_test
                      ? `sandbox ${message.status}`
                      : message.status}
                </Badge>
                <span className="font-mono text-[11px] text-muted-foreground">
                  From: {message.sender_id || "Africa's Talking default"}
                </span>
                <span className="font-mono text-[11px] text-muted-foreground">
                  To: {message.to}
                </span>
                <span className="ml-auto text-[11px] text-muted-foreground">
                  {formatRelative(message.created_at)}
                </span>
              </div>
              <p className="text-sm">{message.message}</p>
              {message.provider_id && (
                <p className="font-mono text-[10px] text-muted-foreground">
                  Provider ID: {message.provider_id}
                </p>
              )}
              {message.error && (
                <p className="text-[11px] text-destructive">{message.error}</p>
              )}
            </li>
          ))}
        </ul>
      )}
    </SectionCard>
  );
}
